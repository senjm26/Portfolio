// Converts siteConfig.name into Barlow Condensed 700 outlines (uppercase, like
// shop signage) so the hero's laser can trace the real letter contours.
// Runs automatically before `npm run dev` / `npm run build`; output is
// src/data/nameGlyphs.ts.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const FONT_SIZE = 200;
const PAD = 24;
const LETTER_SPACING = 0.04; // em

const site = readFileSync(new URL("../src/data/site.ts", import.meta.url), "utf8");
const name = site.match(/\bname:\s*"([^"]+)"/)?.[1];
if (!name) throw new Error("Could not find siteConfig.name in src/data/site.ts");

const fontPath = require.resolve("@fontsource/barlow-condensed/files/barlow-condensed-latin-700-normal.woff");
const buf = readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const r = (n) => Math.round(n * 100) / 100;
const toD = (cmds) =>
  cmds
    .map((c) => {
      switch (c.type) {
        case "M": return `M${r(c.x)} ${r(c.y)}`;
        case "L": return `L${r(c.x)} ${r(c.y)}`;
        case "Q": return `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
        case "C": return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
        default: return "Z";
      }
    })
    .join("");

let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
const glyphs = [];

for (const path of font.getPaths(name.toUpperCase(), 0, 0, FONT_SIZE, { letterSpacing: LETTER_SPACING })) {
  if (!path.commands.length) continue; // spaces

  const contours = [];
  for (const cmd of path.commands) {
    if (cmd.type === "M") contours.push([]);
    contours[contours.length - 1].push(cmd);
  }

  const bb = path.getBoundingBox();
  minX = Math.min(minX, bb.x1);
  minY = Math.min(minY, bb.y1);
  maxX = Math.max(maxX, bb.x2);
  maxY = Math.max(maxY, bb.y2);

  glyphs.push({ d: toD(path.commands), contours: contours.map(toD) });
}

const viewBox = [r(minX - PAD), r(minY - PAD), r(maxX - minX + PAD * 2), r(maxY - minY + PAD * 2)];

writeFileSync(
  new URL("../src/data/nameGlyphs.ts", import.meta.url),
  `// Generated by scripts/generate-name-glyphs.mjs from siteConfig.name - do not edit by hand.

export interface NameGlyph {
  /** Full glyph outline, used for the hole */
  d: string;
  /** Each closed contour on its own, traced one at a time by the laser */
  contours: string[];
}

export const nameGlyphs = {
  text: ${JSON.stringify(name)},
  viewBox: ${JSON.stringify(viewBox.join(" "))},
  glyphs: ${JSON.stringify(glyphs, null, 2)} as NameGlyph[],
};
`
);

console.log(`nameGlyphs: "${name}" → ${glyphs.length} glyphs`);
